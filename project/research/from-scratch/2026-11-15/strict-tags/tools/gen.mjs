// Strict Tags generator: asks Tailwind's own design system (built from the app's theme) for every
// class and variant it knows, and writes them as TypeScript: a union tsc checks class text against,
// and one function per variant. Nothing is hand-listed, so the types cannot drift from Tailwind.
//   node tools/gen.mjs <theme.css> <out-dir>
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";

const [themePath, outDir] = process.argv.slice(2);
if (!themePath || !outDir) {
  console.error("usage: node gen.mjs <theme.css> <out-dir>");
  process.exit(2);
}
const require = createRequire(resolve(process.env.TAILWIND_FROM ?? process.cwd(), "noop.js"));
const twModule = await import(require.resolve("tailwindcss"));
const loadDesignSystem = twModule.__unstable__loadDesignSystem ?? twModule.default.__unstable__loadDesignSystem;
const twDir = dirname(require.resolve("tailwindcss/package.json"));
export const design = await loadDesignSystem(readFileSync(themePath, "utf8"), {
  base: dirname(resolve(themePath)),
  loadStylesheet: async (id, base) => {
    const path = id === "tailwindcss" ? join(twDir, "index.css") : id.startsWith("tailwindcss/") ? join(twDir, id.slice(12) + (id.endsWith(".css") ? "" : ".css")) : resolve(base, id);
    return { path, base: dirname(path), content: readFileSync(path, "utf8") };
  },
});

const list = design.getClassList();
const classes = list.map(([name]) => name);
const classSet = new Set(classes);
const slashed = list.filter(([, meta]) => meta.modifiers?.length).map(([name]) => name);
const colors = [...design.theme.namespace("--color").keys()].filter((k) => k && !k.includes("--")).sort();

// Roots that take a bracket value (w-[180px]). A root that also takes a theme colour is left out:
// bg-[#fff] would reopen the palette the theme closed.
const roots = [...design.utilities.keys("functional")].filter((r) => !r.startsWith("-") && !r.startsWith("@"));
const isColorRoot = (r) => colors.some((c) => classSet.has(`${r}-${c}`));
const arbitrary = roots.filter((r) => !isColorRoot(r) && design.candidatesToCss([`${r}-[1px]`])[0] !== null);

// Variants. A static one becomes a function named in camelCase (focus-visible -> focusVisible).
// A variant with listed values gets one function per value (group-hover -> groupHover). Anything
// that needs brackets or a free value goes through variant("data-[state=open]", …).
const camel = (s) => s.replace(/^@/, "container-").replace(/^(\d)/, "_$1").replace(/-+([a-z0-9])/g, (_, c) => c.toUpperCase());
const JS_RESERVED = new Set(["in", "default"]);
const named = [];
const free = [];
for (const v of design.getVariants()) {
  if (v.name === "*" || v.name === "**") {
    named.push([v.name === "*" ? "children" : "descendants", v.name]);
    continue;
  }
  if (!v.isArbitrary) named.push([camel(v.name), v.name]);
  for (const value of v.values ?? []) if (/^[a-z0-9-]+$/.test(value)) named.push([camel(`${v.name}-${value}`), `${v.name}-${value}`]);
  if (v.isArbitrary) free.push(v.name);
}
// aria-invalid is the state a server-rendered form uses most and Tailwind accepts any aria-* name.
if (!named.some(([, n]) => n === "aria-invalid")) named.push(["ariaInvalid", "aria-invalid"]);
const seen = new Set();
// Kept only when Tailwind itself compiles the spelling (not-group, group-has and the like need a value).
const fns = named.filter(([fn, name]) => !seen.has(fn) && seen.add(fn) && design.candidatesToCss([`${name}:flex`])[0] !== null);

const q = (s) => JSON.stringify(s);
const union = (xs) => (xs.length ? xs.map(q).join(" | ") : "never");
const out = [];
out.push("// Generated by tools/gen.mjs from the app's Tailwind theme. Do not edit.");
out.push(`// tailwindcss ${require("tailwindcss/package.json").version}: ${classes.length} classes, ${fns.length} variant functions, ${colors.length} theme colours.`);
out.push('import { variantFn } from "./core.ts";');
out.push("");
out.push(`/** Every class of this design system. */\nexport type Tw =\n  | ${classes.map(q).join("\n  | ")};`);
out.push(`/** Classes that take a /modifier (bg-primary/10, text-sm/6). */\nexport type TwSlash =\n  | ${slashed.map(q).join("\n  | ")};`);
out.push(`/** Utilities that take a bracket value (w-[180px]). Colour utilities are left out: the palette is closed. */\nexport type TwBracket = ${union(arbitrary)};`);
out.push(`/** The theme's colours, for messages. */\nexport type TwColor = ${union(colors)};`);
out.push(`/** Utilities that take a theme colour: a palette literal on one of these gets the colour list in its message. */\nexport type TwColorRoot = ${union(roots.filter(isColorRoot))};`);
out.push(`export type TwColorList = ${q(colors.join(", "))};`);
out.push(`/** Variant names that take a free value: variant("data-[state=open]", …). */\nexport type TwFreeVariant = ${union(free)};`);
out.push(`/** Tailwind's spelling of each variant function. */\nexport interface TwVariantFns {\n${fns.map(([fn, name]) => `  ${q(name)}: ${q(fn)};`).join("\n")}\n}`);
out.push("");
for (const [fn, name] of fns) {
  const ident = JS_RESERVED.has(fn) ? `${fn}_` : fn;
  out.push(`/** \`${name}:\` on every class given. */\nexport const ${ident} = variantFn(${q(name)});`);
}
out.push("");
writeFileSync(join(outDir, "tw.gen.ts"), out.join("\n"));
console.log(`${classes.length} classes, ${slashed.length} with a modifier, ${arbitrary.length} bracket roots, ${fns.length} variant functions, ${free.length} free variants, ${colors.length} colours -> ${join(outDir, "tw.gen.ts")}`);
