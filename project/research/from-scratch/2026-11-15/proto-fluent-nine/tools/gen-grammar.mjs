// Generates pkg/src/core/tw-grammar.gen.ts from Tailwind 4.3.3's own design system (default theme):
// the class list split into roots and value kinds, and the variant names. Run: node tools/gen-grammar.mjs
import { __unstable__loadDesignSystem } from "tailwindcss";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const req = createRequire(import.meta.url);
const themeCss = readFileSync(req.resolve("tailwindcss/theme.css"), "utf8");
const ds = await __unstable__loadDesignSystem(themeCss + "\n@tailwind utilities;", { base: process.cwd() });
const version = JSON.parse(readFileSync(req.resolve("tailwindcss/package.json"), "utf8")).version;

const palette = [...ds.theme.namespace("--color").keys()].filter((k) => k && k !== "black" && k !== "white");
const colourKw = ["inherit", "current", "transparent", "black", "white"];
const colours = new Set([...palette, ...colourKw]);
const names = ds.getClassList().map(([n]) => n);

const splits = (s) => {
  const out = [];
  for (let i = s.indexOf("-"); i > 0; i = s.indexOf("-", i + 1)) out.push([s.slice(0, i), s.slice(i + 1)]);
  return out;
};
const isNum = (v) => /^\d+(\.\d+)?$/.test(v);
const isFrac = (v) => /^\d+\/\d+$/.test(v);

const colourRoots = new Set();
const numCount = new Map();
const fracRoots = new Set();
const funcRoots = new Set();
const negRoots = new Set();
const pos = [];
const neg = [];
for (const n of names) (n.startsWith("-") ? neg : pos).push(n);

// A colour root takes at least three palette colours (so font-black, a weight, does not make font one).
const paletteSet = new Set(palette);
const colourCount = new Map();
for (const n of pos) for (const [r, v] of splits(n)) if (paletteSet.has(v)) colourCount.set(r, (colourCount.get(r) ?? 0) + 1);
for (const [r, c] of colourCount) if (c >= 3) colourRoots.add(r);
const isColourClass = (n) => splits(n).some(([r, v]) => colourRoots.has(r) && colours.has(v));
for (const n of pos) {
  const colour = isColourClass(n);
  for (const [r, v] of splits(n)) {
    funcRoots.add(r);
    if (colour) continue;
    if (isNum(v)) numCount.set(r, (numCount.get(r) ?? 0) + 1);
    if (isFrac(v)) fracRoots.add(r);
  }
}
// A root takes any number when Tailwind suggests at least three numeric values for it (p-*, grid-cols-*, z-*).
const numRoots = new Set([...numCount].filter(([, c]) => c >= 3).map(([r]) => r));
for (const n of neg) for (const [r, v] of splits(n.slice(1))) if (isNum(v) || isFrac(v) || v === "px") negRoots.add(r);

const covered = (n) => splits(n).some(([r, v]) =>
  (colourRoots.has(r) && colours.has(v)) || (numRoots.has(r) && isNum(v)) || (fracRoots.has(r) && isFrac(v)));
// Bare functional utilities with a default value (rounded, shadow, blur…) are not in the class list.
const bare = [...funcRoots].filter((r) => !names.includes(r) && ds.candidatesToCss([r])[0] != null);
const keywords = [...pos.filter((n) => !covered(n)), ...bare];
const negKeywords = neg.filter((n) => !splits(n.slice(1)).some(([r, v]) => negRoots.has(r) && (isNum(v) || isFrac(v) || v === "px")));

// Theme-keyed roots: a custom token from FluentCustom* is valid after these.
const radiusRoots = [...funcRoots].filter((r) => /^rounded(-|$)/.test(r) && names.includes(`${r}-lg`));
const variants = ds.getVariants();
const staticVariants = variants.filter((v) => !v.isArbitrary && v.values.length === 0).map((v) => v.name);
const breakpoints = variants.find((v) => v.name === "max").values;
const containers = variants.find((v) => v.name === "@").values;
const compoundable = variants.find((v) => v.name === "group").values.filter((v) => !["not", "group", "peer", "in", "has", "aria", "data", "nth", "nth-last", "nth-of-type", "nth-last-of-type"].includes(v));

const u = (xs) => [...new Set(xs)].sort().map((x) => JSON.stringify(x)).join(" | ") || "never";
const shades = [...new Set(palette.map((p) => p.replace(/^.*-/, "")))];
const paletteNames = [...new Set(palette.map((p) => p.replace(/-[^-]*$/, "")))];

const out = `// Generated by tools/gen-grammar.mjs from tailwindcss ${version}'s default theme. Do not edit.
// ${names.length} classes in Tailwind's class list: ${keywords.length} keywords, ${negKeywords.length} negative keywords,
// the rest covered by ${colourRoots.size} colour roots, ${numRoots.size} numeric roots and ${fracRoots.size} fraction roots.

export type TwKeyword = ${u(keywords)};
export type TwNegKeyword = ${u(negKeywords)};
export type TwColourRoot = ${u([...colourRoots])};
export type TwNumRoot = ${u([...numRoots])};
export type TwFracRoot = ${u([...fracRoots])};
export type TwNegRoot = ${u([...negRoots])};
export type TwFuncRoot = ${u([...funcRoots])};
export type TwRadiusRoot = ${u(radiusRoots)};
export type TwPaletteName = ${u(paletteNames)};
export type TwShade = ${u(shades)};
export type TwStaticVariant = ${u(staticVariants)};
export type TwCompoundable = ${u(compoundable)};
export type TwBreakpoint = ${u(breakpoints)};
export type TwContainer = ${u(containers)};
`;
const dest = fileURLToPath(new URL("../pkg/src/core/tw-grammar.gen.ts", import.meta.url));
writeFileSync(dest, out);
console.log(`wrote ${dest}: ${out.length} B; keywords ${keywords.length}, neg ${negKeywords.length}, colourRoots ${colourRoots.size}, numRoots ${numRoots.size}, fracRoots ${fracRoots.size}, negRoots ${negRoots.size}, funcRoots ${funcRoots.size}, staticVariants ${staticVariants.length}`);

// Tombstones: fluent-html 8's styling methods, the unprefixed attribute names, and names removed
// before 9, as non-callable members whose type names the fix (TS2349 prints it).
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase()).replace(/^xl2$/, "2xl");
const keywordSet = new Set(keywords);
const variantSet = new Set([...staticVariants, "group-hover", "peer-checked"]);
const special = {
  cssProp: '.tw("[mask-repeat:no-repeat]"): an arbitrary property in the class text',
  neg: '.tw("-mt-2"): negative values are written with a leading minus',
  variant: '.tw("aria-invalid:border-danger"): every variant is a prefix in the class text',
  gradient: '.tw("bg-linear-to-r from-primary to-info")',
  containerQuery: '.tw("@container") on the parent, .tw("@md:flex") on the child',
  anchorName: '.setStyle("anchor-name: --menu")',
  positionAnchor: '.setStyle("position-anchor: --menu")',
  positionArea: '.setStyle("position-area: bottom")',
  viewTransitionName: '.setStyle("view-transition-name: card")',
  transform: '.tw("rotate-45 scale-95"): Tailwind 4 needs no transform class',
  disabled: '.toggle("disabled") for the attribute, .tw("disabled:opacity-50") for the variant',
  checked: '.toggle("checked") for the attribute, .tw("checked:bg-primary") for the variant',
  hidden: '.tw("hidden") for display:none, .toggle("hidden") for the attribute',
  select: '.tw("select-none") for user-select; a <select> is Select(...) or f.select(...)',
  scrollP: '.tw("scroll-p-4")',
  wrap: '.tw("flex-wrap") or .tw("text-wrap")',
  group: '.tw("group") on the parent, .tw("group-hover:underline") on the child',
  peer: '.tw("peer") on the input, .tw("peer-checked:bg-primary") on the sibling',
  groupHover: '.tw("group-hover:underline")',
  peerChecked: '.tw("peer-checked:bg-primary")',
  srOnly: '.tw("sr-only")',
  dark: '.tw("dark:bg-surface")',
};
const methods = readFileSync(new URL("./fh8-styling-methods.txt", import.meta.url), "utf8").split("\n").filter(Boolean)
  .filter((m) => m !== "cssClass");
const hint = (m) => {
  if (special[m]) return special[m];
  const k = kebab(m);
  if (variantSet.has(k)) return `.tw("${k}:…"): a variant is a prefix in the class text`;
  if (keywordSet.has(k)) return `.tw("${k}")`;
  return `.tw("${k}-…"): styling is Tailwind class text`;
};
const attrs = {
  src: ".setSrc(url)", href: ".setHref(url) or a verb: .nav(route)", value: ".setValue(v)", type: ".setType(t)",
  name: ".setName(n)", id: ".setId(ids.x)", placeholder: ".setPlaceholder(text)", alt: ".setAlt(text)",
  action: ".nav(route) / .submit(route) on the Form", method: "the route decides the method: .submit(route)",
  target: ".setTarget(t)", rel: ".setRel(r)", required: ".toggle(\"required\")", readonly: ".toggle(\"readonly\")",
  className: ".tw(\"…\")", class: ".tw(\"…\")", classList: ".tw(\"…\")", style: ".tw(\"…\") or .setStyle(\"literal: css\")",
  setClassName: ".tw(\"…\")", addClasses: ".tw(\"…\")", on: ".behavior(…) or an htmx verb; inline on* handlers are refused",
  onClick: ".behavior(…) or an htmx verb; inline on* handlers are refused", textColor: ".tw(\"text-…\")",
attr: ".addAttribute(key, value)", children: "pass children to the factory: Div(a, b)",
  child: undefined, text: undefined,
};
delete attrs.child; delete attrs.text;
// Names Claude Code guessed in round 1's control sessions and the design probes, beyond fluent-html 8's own.
const guesses = {
  flexCol: '.tw("flex flex-col")', flexRow: '.tw("flex flex-row")', flexDirection: '.tw("flex-col") or .tw("flex-row")',
  flexWrap: '.tw("flex-wrap")', textAlign: '.tw("text-left") / .tw("text-center") / .tw("text-right")',
  overflowX: '.tw("overflow-x-auto")', overflowY: '.tw("overflow-y-auto")', notSrOnly: '.tw("not-sr-only")',
  fontWeight: '.tw("font-semibold")', fontSize: '.tw("text-sm")', textSize: '.tw("text-sm")', bgColor: '.tw("bg-surface")',
  borderColor: '.tw("border-line")', borderRadius: '.tw("rounded-card")', itemsCenter: '.tw("items-center")',
  justifyBetween: '.tw("justify-between")', justifyCenter: '.tw("justify-center")', padding: '.tw("p-4")',
  margin: '.tw("m-4")', width: '.tw("w-full")', height: '.tw("h-12")', maxWidth: '.tw("max-w-lg")',
  minHeight: '.tw("min-h-screen")', display: '.tw("block") / .tw("hidden") / .tw("flex")', position: '.tw("relative")',
  tl: '.tw("…")', classes: '.tw("…")',
};
const lines = [...methods.map((m) => [m, hint(m)]), ...Object.entries(guesses).filter(([k]) => !methods.includes(k)), ...Object.entries(attrs).filter(([k]) => !methods.includes(k))]
  .map(([m, h]) => `    readonly ${/^[a-z]\w*$/i.test(m) ? m : JSON.stringify(m)}: UseInstead<${JSON.stringify(h)}>;`);
const tomb = `// Generated by tools/gen-grammar.mjs. Do not edit.
// Members that are not callable: a guessed fluent-html 8 styling method or an unprefixed attribute
// name fails with TS2349, and the type it prints is the fix.
import type { UseInstead } from "./tw-types.js";

declare module "./tag.js" {
  interface Tag {
${lines.join("\n")}
  }
}
export {};
`;
writeFileSync(fileURLToPath(new URL("../pkg/src/core/tw-tombstones.gen.ts", import.meta.url)), tomb);
console.log(`tombstones: ${lines.length}`);
