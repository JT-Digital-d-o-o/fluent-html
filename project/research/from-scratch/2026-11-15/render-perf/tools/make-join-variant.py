"""Writes src/hh-join.ts and src/hx-join.ts: the same runtime, with Array.join in place of
`+=` in html`` and in array holes. It exists to measure rope against flat-string building.

    python3 -I tools/make-join-variant.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
s = (ROOT / "src/hh.ts").read_text(encoding="utf-8")

a = '''  const st = t.statics;
  const kinds = t.kinds;
  let out = st[0]!;
  for (let i = 0; i < values.length; i++) {
    const v = values[i];
    out += (kinds[i] === K_TEXT && typeof v === "string" ? esc(v) : hole(t, i, v)) + st[i + 1]!;
  }
  return new Html(out);
}

/** A template whose single root'''
b = '''  const st = t.statics;
  const kinds = t.kinds;
  const n = values.length;
  const parts = new Array<string>(2 * n + 1);
  parts[0] = st[0]!;
  for (let i = 0; i < n; i++) {
    const v = values[i];
    parts[2 * i + 1] = kinds[i] === K_TEXT && typeof v === "string" ? esc(v) : hole(t, i, v);
    parts[2 * i + 2] = st[i + 1]!;
  }
  return new Html(parts.join(""));
}

/** A template whose single root'''
assert s.count(a) == 1
s = s.replace(a, b)
